-- Public Intro still poster (Infrastructure Optimization & Security Hardening V1, Mazen's task 2026-10-27) - GamID TESTING only. Additive: no existing row,
-- object, Intro, derivative, share copy or accepted contract changes.
--
-- The public Intro waits for Play on the owner's chosen frame (DEC-0012). Until now the visitor's player showed that frame by seeking the video itself, which
-- downloads 0.4-1.8 MB of every Intro on every visit (measured 2026-10-27) even when the visitor never presses Play. A poster is a still image of EXACTLY that
-- frame (the last frame presented at or before the chosen time, as a paused browser shows it), at the Intro's own size, generated by the same worker Job from
-- the private D3 derivative. The player shows it in the same element and loads the video only on Play. Without a ready poster nothing changes.
--
--   1. bucket intro-posters: private, WebP only, at most 1 MiB. Its only read path is the storage policy below, for a CURRENT ready poster of a PUBLIC GamID
--      (the same shape as the Intro and share-copy read policies). Only the worker (service role) writes and deletes.
--   2. public.intro_posters: registry + queue (pending -> processing -> ready | failed | superseded), claimed with SKIP LOCKED and per-attempt claim tokens, a
--      lost-worker reclaim after 20 minutes, at most 2 attempts. One poster per (Intro, frame): the first frame (poster_ms 0) of the active Intro, and the
--      owner's chosen thumbnail frame while one is chosen.
--   3. a poster is queued by the database itself when an Intro becomes active or a thumbnail frame is chosen (private.enqueue_intro_posters); existing Intros
--      are NOT backfilled here (a separate, explicit step once the worker image that generates posters is deployed).
--   4. visitors: public.get_public_intro_poster(handle) returns the frame the page shows (the chosen frame while its share copy is ready, else the first frame,
--      exactly as get_public_intro_share decided before) and that frame's ready poster, if there is one.
--   5. quota: like the share copy, this internal still never counts toward the owner's unchanged 200 MB.
--   6. lifecycle: a storage-driven sweep deletes every poster object that is not a current ready poster or an in-flight attempt, after a grace period.
--   7. abuse bound: at most 20 posters may be queued per profile per hour (each one starts a worker execution); beyond that the page keeps today's behavior.
-- Rollback: drop the triggers, the policy, the functions and the table; reverse the two in-place usage patches; delete the bucket's objects, then the bucket.

-- ---------------------------------------------------------------------------------------------
-- 1. Storage
-- ---------------------------------------------------------------------------------------------
insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values ('intro-posters', 'intro-posters', false, 1048576, array['image/webp'])
on conflict (id) do update set public = excluded.public, file_size_limit = excluded.file_size_limit, allowed_mime_types = excluded.allowed_mime_types;

-- ---------------------------------------------------------------------------------------------
-- 2. The registry + queue
-- ---------------------------------------------------------------------------------------------
create table public.intro_posters (
  poster_id uuid primary key default gen_random_uuid(),
  profile_id uuid not null references public.profiles(profile_id) on delete cascade,
  owner_user_id uuid not null,
  job_id uuid not null references public.intro_processing_jobs(job_id) on delete cascade,
  poster_ms integer not null check (poster_ms between 0 and 31000),
  state text not null default 'pending',
  attempts integer not null default 0,
  claim_token uuid,
  poster_path text,
  poster_bytes integer,
  poster_width integer,
  poster_height integer,
  failure_code text,
  created_at timestamptz not null default now(),
  started_at timestamptz,
  completed_at timestamptz,
  updated_at timestamptz not null default now(),
  constraint intro_posters_state check (state in ('pending', 'processing', 'ready', 'failed', 'superseded')),
  constraint intro_posters_path check (poster_path is null or (poster_path ~ '^[0-9a-f-]{36}/[0-9a-f-]{36}/[0-9a-f-]{36}/[0-9a-f-]{36}\.webp$' and split_part(poster_path, '/', 1) = owner_user_id::text)),
  constraint intro_posters_ready check (state <> 'ready' or (poster_path is not null and poster_bytes between 1 and 1048576 and poster_width > 0 and poster_height > 0))
);
-- at most one live poster per Intro frame
create unique index intro_posters_one_live on public.intro_posters (job_id, poster_ms) where state in ('pending', 'processing', 'ready');
create index intro_posters_pending_idx on public.intro_posters (created_at) where state = 'pending';
create index intro_posters_profile_created_idx on public.intro_posters (profile_id, created_at desc);
alter table public.intro_posters enable row level security;
revoke all on table public.intro_posters from public, anon, authenticated;

-- a poster is current while its Intro is the profile's ACTIVE, ready Intro and its frame is the first frame or the owner's current choice for that Intro
create function private.intro_poster_is_current(candidate_poster_id uuid)
returns boolean
language sql stable security definer
set search_path = ''
as $$
  select exists (
    select 1
    from public.intro_posters r
    join public.profile_intro_settings s on s.profile_id = r.profile_id
    join public.intro_processing_jobs j on j.job_id = s.active_job_id
    where r.poster_id = candidate_poster_id
      and s.active_job_id = r.job_id
      and (r.poster_ms = 0 or (s.thumbnail_job_id = r.job_id and s.thumbnail_ms = r.poster_ms))
      and j.state = 'ready' and j.derivative_path is not null and j.derivative_deleted_at is null
  );
$$;

-- the public read path: a current ready poster of a PUBLIC GamID (mirrors private.intro_share_is_public)
create function private.intro_poster_is_public(candidate_path text)
returns boolean
language sql stable security definer
set search_path = ''
as $$
  select exists (
    select 1
    from public.intro_posters r
    join public.profiles p on p.profile_id = r.profile_id
    join public.entities e on e.entity_id = p.entity_id
    where r.poster_path = candidate_path and r.state = 'ready'
      and e.entity_type = 'SOLO' and e.visibility = 'PUBLIC'
      and private.intro_poster_is_current(r.poster_id)
  );
$$;

create policy "public identity intro posters are readable"
on storage.objects for select to anon, authenticated
using (bucket_id = 'intro-posters' and private.intro_poster_is_public(name));

-- ---------------------------------------------------------------------------------------------
-- 3. Queueing (database-driven: no client can request a poster)
-- ---------------------------------------------------------------------------------------------
-- Queues the missing posters of one profile's ACTIVE ready Intro: its first frame and, while one is chosen for it, the owner's thumbnail frame. Posters that are
-- no longer current are superseded first. Silent and bounded: beyond 20 queued per profile per hour nothing is queued (the page keeps seeking the video).
create function private.enqueue_intro_posters(candidate_profile_id uuid)
returns integer
language plpgsql volatile security definer
set search_path = ''
as $$
declare
  settings public.profile_intro_settings%rowtype;
  intro public.intro_processing_jobs%rowtype;
  wanted integer;
  queued integer := 0;
begin
  update public.intro_posters r set state = 'superseded', claim_token = null, completed_at = coalesce(r.completed_at, now()), updated_at = now()
  where r.profile_id = candidate_profile_id and r.state in ('pending', 'processing', 'ready') and not private.intro_poster_is_current(r.poster_id);
  select * into settings from public.profile_intro_settings s where s.profile_id = candidate_profile_id;
  if settings.active_job_id is null then return 0; end if;
  select * into intro from public.intro_processing_jobs j
  where j.job_id = settings.active_job_id and j.state = 'ready' and j.derivative_path is not null and j.derivative_deleted_at is null;
  if intro.job_id is null then return 0; end if;
  foreach wanted in array array[0, case when settings.thumbnail_job_id = intro.job_id then settings.thumbnail_ms end] loop
    continue when wanted is null;
    continue when exists (select 1 from public.intro_posters r where r.job_id = intro.job_id and r.poster_ms = wanted and r.state in ('pending', 'processing', 'ready'));
    exit when (select count(*) from public.intro_posters r where r.profile_id = candidate_profile_id and r.created_at > now() - interval '1 hour') >= 20;
    insert into public.intro_posters (profile_id, owner_user_id, job_id, poster_ms) values (candidate_profile_id, intro.owner_user_id, intro.job_id, wanted);
    queued := queued + 1;
  end loop;
  return queued;
end;
$$;

create function private.queue_intro_posters_on_settings()
returns trigger
language plpgsql security definer
set search_path = ''
as $$
begin
  perform private.enqueue_intro_posters(new.profile_id);
  return new;
end;
$$;

create trigger queue_intro_posters
after insert or update of active_job_id, thumbnail_job_id, thumbnail_ms on public.profile_intro_settings
for each row
execute function private.queue_intro_posters_on_settings();

-- ---------------------------------------------------------------------------------------------
-- 4. Visitors: the frame the public page shows and that frame's ready poster, for a PUBLIC GamID with a ready Intro; else no row
-- ---------------------------------------------------------------------------------------------
-- poster_ms: the chosen frame while its share copy is ready (exactly what get_public_intro_share reported before), else null = the Intro's first frame.
-- poster_path / poster_width / poster_height: that frame's current ready poster, or null (the page then seeks the video as before).
create function private.get_public_intro_poster_impl(candidate_handle text)
returns table (poster_ms integer, poster_path text, poster_width integer, poster_height integer)
language sql stable security definer
set search_path = ''
as $$
  with intro as (
    select p.profile_id, s.active_job_id job_id,
      (select c.thumbnail_ms from private.get_public_intro_share_impl(candidate_handle) c limit 1) chosen_ms
    from public.entities e
    join public.profiles p on p.entity_id = e.entity_id
    join public.profile_intro_settings s on s.profile_id = p.profile_id
    join public.intro_processing_jobs j on j.job_id = s.active_job_id and j.state = 'ready' and j.derivative_path is not null and j.derivative_deleted_at is null
    where e.gamid_handle = private.normalize_handle(candidate_handle)
      and e.entity_type = 'SOLO'
      and e.visibility = 'PUBLIC'
    limit 1
  )
  select i.chosen_ms, r.poster_path, r.poster_width, r.poster_height
  from intro i
  left join lateral (
    select x.poster_path, x.poster_width, x.poster_height from public.intro_posters x
    where x.job_id = i.job_id and x.poster_ms = coalesce(i.chosen_ms, 0) and x.state = 'ready' and private.intro_poster_is_current(x.poster_id)
    limit 1
  ) r on true;
$$;

-- ---------------------------------------------------------------------------------------------
-- 5. The worker (service role only)
-- ---------------------------------------------------------------------------------------------
create function private.worker_claim_intro_poster_impl()
returns table (poster_id uuid, claim_token uuid, owner_user_id uuid, job_id uuid, derivative_path text, derivative_bytes bigint, intro_duration_ms integer,
  intro_width integer, intro_height integer, poster_ms integer, poster_path text)
language plpgsql volatile security definer
set search_path = ''
as $$#variable_conflict use_column

declare
  picked public.intro_posters%rowtype;
  intro public.intro_processing_jobs%rowtype;
  token uuid := gen_random_uuid();
  path text;
begin
  update public.intro_posters r set state = 'failed', failure_code = 'PROCESSING_TIMED_OUT', claim_token = null, completed_at = now(), updated_at = now()
  where r.state = 'processing' and r.started_at < now() - interval '20 minutes' and r.attempts >= 2;
  update public.intro_posters r set state = 'superseded', claim_token = null, completed_at = now(), updated_at = now()
  where r.state in ('pending', 'processing') and not private.intro_poster_is_current(r.poster_id);
  select * into picked from public.intro_posters r
  where r.state = 'pending' or (r.state = 'processing' and r.started_at < now() - interval '20 minutes' and r.attempts < 2)
  order by r.created_at for update skip locked limit 1;
  if picked.poster_id is null then return; end if;
  select * into intro from public.intro_processing_jobs j where j.job_id = picked.job_id;
  path := picked.owner_user_id::text || '/' || picked.job_id::text || '/' || picked.poster_id::text || '/' || token::text || '.webp';
  update public.intro_posters r set state = 'processing', attempts = r.attempts + 1, claim_token = token, poster_path = path, started_at = now(), updated_at = now()
  where r.poster_id = picked.poster_id;
  return query select picked.poster_id, token, picked.owner_user_id, picked.job_id, intro.derivative_path, intro.output_size_bytes, intro.output_duration_ms,
    intro.output_width, intro.output_height, picked.poster_ms, path;
end;
$$;

-- after the worker's own validation passed and the object was written: mark READY, only while it is still current and only at the Intro's own size
create function private.worker_complete_intro_poster_impl(candidate_poster_id uuid, candidate_claim_token uuid, candidate_path text, candidate_bytes integer,
  candidate_width integer, candidate_height integer)
returns table (poster_id uuid, state text)
language plpgsql volatile security definer
set search_path = ''
as $$#variable_conflict use_column

declare
  job public.intro_posters%rowtype;
  intro public.intro_processing_jobs%rowtype;
  stored record;
begin
  select * into job from public.intro_posters r where r.poster_id = candidate_poster_id and r.state = 'processing' for update;
  if job.poster_id is null or job.claim_token is distinct from candidate_claim_token then raise exception using errcode = '22023', message = 'INTRO_POSTER_NOT_CLAIMED'; end if;
  if candidate_path is distinct from job.poster_path then raise exception using errcode = '22023', message = 'INVALID_INTRO_POSTER_PATH'; end if;
  if not private.intro_poster_is_current(job.poster_id) then raise exception using errcode = '22023', message = 'INTRO_POSTER_SUPERSEDED'; end if;
  select * into intro from public.intro_processing_jobs j where j.job_id = job.job_id;
  select (o.metadata ->> 'size')::bigint size, o.metadata ->> 'mimetype' mime into stored from storage.objects o where o.bucket_id = 'intro-posters' and o.name = job.poster_path;
  if stored.size is null then raise exception using errcode = 'P0002', message = 'INTRO_POSTER_NOT_FOUND'; end if;
  if stored.size is distinct from candidate_bytes::bigint or stored.size > 1048576 or stored.mime is distinct from 'image/webp' then raise exception using errcode = '22023', message = 'INTRO_POSTER_OBJECT_MISMATCH'; end if;
  if candidate_width is distinct from intro.output_width or candidate_height is distinct from intro.output_height then raise exception using errcode = '22023', message = 'INTRO_POSTER_GEOMETRY_CHANGED'; end if;
  update public.intro_posters r set state = 'ready', claim_token = null, poster_bytes = stored.size, poster_width = candidate_width, poster_height = candidate_height,
    failure_code = null, completed_at = now(), updated_at = now()
  where r.poster_id = job.poster_id;
  return query select job.poster_id, 'ready'::text;
end;
$$;

create function private.worker_fail_intro_poster_impl(candidate_poster_id uuid, candidate_claim_token uuid, candidate_code text)
returns void
language plpgsql volatile security definer
set search_path = ''
as $$
begin
  update public.intro_posters r set state = 'failed', claim_token = null,
    failure_code = left(regexp_replace(upper(coalesce(candidate_code, 'INTRO_POSTER_FAILED')), '[^A-Z0-9_]', '_', 'g'), 64), completed_at = now(), updated_at = now()
  where r.poster_id = candidate_poster_id and r.state = 'processing' and r.claim_token = candidate_claim_token;
end;
$$;

-- the sweep: every poster object that is not a current READY poster and not the current in-flight attempt, once older than the grace period
create function private.worker_intro_poster_sweep_impl(candidate_limit integer)
returns table (object_path text)
language sql stable security definer
set search_path = ''
as $$
  select o.name
  from storage.objects o
  where o.bucket_id = 'intro-posters'
    and o.created_at < now() - interval '10 minutes'
    and not exists (
      select 1 from public.intro_posters r
      where r.poster_path = o.name
        and ((r.state = 'ready' and private.intro_poster_is_current(r.poster_id)) or (r.state = 'processing' and r.claim_token is not null)))
  order by o.created_at
  limit least(greatest(coalesce(candidate_limit, 20), 1), 50);
$$;

-- ---------------------------------------------------------------------------------------------
-- 6. Quota: the internal poster never counts toward the owner's storage. Patched IN PLACE from the live definitions (after the share copy's patch), so every
--    other part of them is kept exactly; a missing target aborts the migration.
-- ---------------------------------------------------------------------------------------------
do $$
declare original text; revised text;
begin
  foreach original in array array[pg_get_functiondef('private.usage_stored_bytes(uuid)'::regprocedure), pg_get_functiondef('private.get_my_usage_impl()'::regprocedure)] loop
    revised := replace(original, $o$o.bucket_id not in ('wall-video-renditions','intro-share-copies')$o$, $n$o.bucket_id not in ('wall-video-renditions','intro-share-copies','intro-posters')$n$);
    if revised = original then raise exception 'INTRO_POSTER_USAGE_PATCH_FAILED'; end if;
    execute revised;
  end loop;
end $$;

