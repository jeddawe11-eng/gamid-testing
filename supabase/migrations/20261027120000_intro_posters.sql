-- ---------------------------------------------------------------------------------------------
-- 8. Dispatch: the same Vault-held dispatcher as the Intro / share-copy pipeline. The dispatcher accepts this table only once its updated build is deployed;
--    until then (or without configuration) a poster simply waits for the next worker run - the page keeps seeking the video meanwhile.
-- ---------------------------------------------------------------------------------------------
create or replace function private.dispatch_intro_poster()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  dispatcher_url text;
  dispatcher_secret text;
begin
  select decrypted_secret into dispatcher_url from vault.decrypted_secrets where name = 'gamid_intro_dispatch_url_testing';
  select decrypted_secret into dispatcher_secret from vault.decrypted_secrets where name = 'gamid_intro_dispatch_secret_testing';
  if dispatcher_url is null or dispatcher_secret is null then return new; end if;
  perform net.http_post(
    url := dispatcher_url || '/dispatch',
    headers := jsonb_build_object('Content-Type', 'application/json', 'x-gamid-dispatch-secret', dispatcher_secret),
    body := jsonb_build_object('type', 'INSERT', 'schema', 'public', 'table', 'intro_posters', 'record', jsonb_build_object('job_id', new.poster_id, 'state', new.state)),
    timeout_milliseconds := 5000
  );
  return new;
end;
$$;
revoke all on function private.dispatch_intro_poster() from public, anon, authenticated;

create trigger dispatch_intro_poster
after insert on public.intro_posters
for each row
when (new.state = 'pending')
execute function private.dispatch_intro_poster();
